
/**
 * The return values given by typeof when used on primitive types 
 */
const Primitives = Object.freeze({
    /** @type {string} */
    STRING: typeof "string",
    /** @type {string} */
    NUMBER: typeof 10,
    /** @type {string} */
    BOOLEAN: typeof true,
    /** @type {string} */
    UNDEFINED: typeof undefined
})
    
export {
    Primitives
}

